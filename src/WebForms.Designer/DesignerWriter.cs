using System.Text;

namespace WebForms.Designer;

/// <summary>Byte-level formatting choices. Visual Studio and Rider differ only in these.</summary>
public sealed record DesignerStyle(
    bool Bom,
    bool HeaderTrailingSpace,
    bool IndentedBlankLines,
    string NewLine,
    int BlankLinesBeforeClass = 2,
    bool BlankLineBeforeEndClass = false)
{
    /// <summary>Visual Studio (as found in most of the corpus): BOM, the header's "regenerated. " keeps its trailing space, blank lines are empty.</summary>
    public static readonly DesignerStyle VisualStudio = new(true, true, false, "\r\n");

    /// <summary>Visual Studio when the designer is regenerated without going through the VB editor (CodeDOM output: blank lines indented with 4 spaces).</summary>
    public static readonly DesignerStyle VisualStudioCodeDom = new(true, true, true, "\r\n");

    /// <summary>Rider: as Visual Studio, but trailing whitespace trimmed (honours .editorconfig trim_trailing_whitespace).</summary>
    public static readonly DesignerStyle Rider = new(true, false, false, "\r\n");

    /// <summary>Detect the style of an existing designer file so regeneration does not churn formatting.</summary>
    public static DesignerStyle Detect(byte[] existing)
    {
        bool bom = existing.Length >= 3 && existing[0] == 0xEF && existing[1] == 0xBB && existing[2] == 0xBF;
        var text = Encoding.UTF8.GetString(existing, bom ? 3 : 0, existing.Length - (bom ? 3 : 0));
        string nl = text.Contains("\r\n", StringComparison.Ordinal) || !text.Contains('\n') ? "\r\n" : "\n";
        bool headerSpace = text.Contains("regenerated. " + nl, StringComparison.Ordinal);
        var lines = text.Split('\n').Select(l => l.TrimEnd('\r')).ToList();
        bool indented = lines.Any(l => l.Length > 0 && l.Trim().Length == 0);

        // Blank lines between "Option Explicit On" and the class (2 in current IDEs; 1 or 3 seen in old files).
        // Stored as the count for a class without a Namespace block, which gets one more than a namespaced one.
        int blankBefore = 2;
        int opt = lines.FindIndex(l => l.StartsWith("Option Explicit", StringComparison.OrdinalIgnoreCase));
        if (opt >= 0)
        {
            int n = 0;
            int i = opt + 1;
            for (; i < lines.Count && lines[i].Trim().Length == 0; i++)
            {
                n++;
            }

            if (i < lines.Count && lines[i].StartsWith("Namespace ", StringComparison.OrdinalIgnoreCase))
            {
                n++;
            }

            blankBefore = Math.Clamp(n, 1, 3);
        }

        // Some Rider versions leave a blank line before "End Class" when the class has members.
        int end = lines.FindLastIndex(l => l.Trim().Equals("End Class", StringComparison.OrdinalIgnoreCase));
        bool blankBeforeEnd = end > 0 && lines[end - 1].Trim().Length == 0 && !lines[end - 2].TrimStart().StartsWith("Partial", StringComparison.OrdinalIgnoreCase);

        return new DesignerStyle(bom, headerSpace, indented, nl, blankBefore, blankBeforeEnd);
    }
}

public static class DesignerWriter
{
    public static string Render(DesignerModel model, DesignerStyle style)
    {
        var sb = new StringBuilder(1024 + (model.Fields.Count * 400));
        string nl = style.NewLine;

        void Line(string s = "") => sb.Append(s).Append(nl);

        Line("'------------------------------------------------------------------------------");
        Line("' <auto-generated>");
        Line("'     This code was generated by a tool.");
        Line("'");
        Line("'     Changes to this file may cause incorrect behavior and will be lost if");
        Line(style.HeaderTrailingSpace ? "'     the code is regenerated. " : "'     the code is regenerated.");
        Line("' </auto-generated>");
        Line("'------------------------------------------------------------------------------");
        Line();
        Line("Option Strict On");
        Line("Option Explicit On");

        // CodeDOM writes one blank line for the (empty) global namespace and one before the first declaration, so a
        // class in a Namespace block has one blank line fewer before "Namespace X" (verified against Visual Studio).
        int blankLines = model.Namespace is null ? style.BlankLinesBeforeClass : Math.Max(1, style.BlankLinesBeforeClass - 1);
        for (int i = 0; i < blankLines; i++)
        {
            Line();
        }

        string indent = "";
        if (model.Namespace is not null)
        {
            Line("Namespace " + model.Namespace);
            indent = "    ";
            Line(style.IndentedBlankLines ? indent : "");
        }

        Line(indent + "Partial Public Class " + model.ClassName);
        string m = indent + "    ";

        void Blank() => Line(style.IndentedBlankLines ? indent + "    " : "");

        foreach (var f in model.Fields)
        {
            Blank();
            Line(m + "'''<summary>");
            Line(m + "'''" + f.Name + " control.");
            Line(m + "'''</summary>");
            Line(m + "'''<remarks>");
            Line(m + "'''Auto-generated field.");
            Line(m + "'''To modify move field declaration from designer file to code-behind file.");
            Line(m + "'''</remarks>");
            Line(m + "Protected WithEvents " + f.Name + " As " + f.TypeName);
        }

        if (model.MasterTypeName is not null)
        {
            Blank();
            Line(m + "'''<summary>");
            Line(m + "'''Master property.");
            Line(m + "'''</summary>");
            Line(m + "'''<remarks>");
            Line(m + "'''Auto-generated property.");
            Line(m + "'''</remarks>");
            Line(m + "Public Shadows ReadOnly Property Master() As " + model.MasterTypeName);
            Line(m + "    Get");
            Line(m + "        Return CType(MyBase.Master, " + model.MasterTypeName + ")");
            Line(m + "    End Get");
            Line(m + "End Property");
        }

        if (style.BlankLineBeforeEndClass && (model.Fields.Count > 0 || model.MasterTypeName is not null))
        {
            Blank();
        }

        Line(indent + "End Class");
        if (model.Namespace is not null)
        {
            Line("End Namespace");
        }

        return sb.ToString();
    }

    public static byte[] Encode(string text, DesignerStyle style)
    {
        var body = Encoding.UTF8.GetBytes(text);
        if (!style.Bom)
        {
            return body;
        }

        var bytes = new byte[body.Length + 3];
        bytes[0] = 0xEF;
        bytes[1] = 0xBB;
        bytes[2] = 0xBF;
        body.CopyTo(bytes, 3);
        return bytes;
    }
}
