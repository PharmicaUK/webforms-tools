using System.Text;
using WebForms.Designer;
using WebForms.Markup;

namespace WebForms.Tests;

public class WriterTests
{
    private static readonly DesignerModel Model = new()
    {
        ClassName = "Blank",
        Namespace = null,
        Fields = [new DesignerField("form1", "Global.System.Web.UI.HtmlControls.HtmlForm", default)],
        MasterTypeName = null,
    };

    // Byte-for-byte what Visual Studio writes (checked against designers saved by VS 2022).
    private const string VisualStudioText =
        "'------------------------------------------------------------------------------\r\n" +
        "' <auto-generated>\r\n" +
        "'     This code was generated by a tool.\r\n" +
        "'\r\n" +
        "'     Changes to this file may cause incorrect behavior and will be lost if\r\n" +
        "'     the code is regenerated. \r\n" +
        "' </auto-generated>\r\n" +
        "'------------------------------------------------------------------------------\r\n" +
        "\r\n" +
        "Option Strict On\r\n" +
        "Option Explicit On\r\n" +
        "\r\n" +
        "\r\n" +
        "Partial Public Class Blank\r\n" +
        "\r\n" +
        "    '''<summary>\r\n" +
        "    '''form1 control.\r\n" +
        "    '''</summary>\r\n" +
        "    '''<remarks>\r\n" +
        "    '''Auto-generated field.\r\n" +
        "    '''To modify move field declaration from designer file to code-behind file.\r\n" +
        "    '''</remarks>\r\n" +
        "    Protected WithEvents form1 As Global.System.Web.UI.HtmlControls.HtmlForm\r\n" +
        "End Class\r\n";

    [Fact]
    public void Visual_studio_style()
    {
        Assert.Equal(VisualStudioText, DesignerWriter.Render(Model, DesignerStyle.VisualStudio));
        var bytes = DesignerWriter.Encode(VisualStudioText, DesignerStyle.VisualStudio);
        Assert.Equal([0xEF, 0xBB, 0xBF], bytes[..3]);
    }

    [Fact]
    public void Rider_style_trims_trailing_whitespace()
    {
        var text = DesignerWriter.Render(Model, DesignerStyle.Rider);
        Assert.Contains("regenerated.\r\n", text);
        Assert.DoesNotContain(" \r\n", text);
    }

    [Fact]
    public void Style_detection_round_trips()
    {
        foreach (var style in new[] { DesignerStyle.VisualStudio, DesignerStyle.VisualStudioCodeDom, DesignerStyle.Rider, DesignerStyle.Rider with { Bom = false, BlankLineBeforeEndClass = true } })
        {
            var bytes = DesignerWriter.Encode(DesignerWriter.Render(Model, style), style);
            Assert.Equal(style, DesignerStyle.Detect(bytes));
        }
    }

    [Fact]
    public void Master_property_only_for_a_MasterType_directive_by_default()
    {
        var withMaster = new DesignerModel { ClassName = "P", Namespace = null, Fields = [], MasterTypeName = "App.Site" };
        string Build(byte[]? existing, MasterPropertyMode mode = MasterPropertyMode.Directive) =>
            DesignerOutput.Decode(DesignerOutput.Build(withMaster, existing, new OutputOptions(Master: mode)));

        // <%@ MasterType %> declared: always written, whatever the mode or existing file.
        var declared = withMaster with { MasterTypeDeclared = true };
        Assert.Contains("Public Shadows ReadOnly Property Master() As App.Site", DesignerOutput.Decode(DesignerOutput.Build(declared, null, new OutputOptions())));

        // MasterPageFile only, like Visual Studio: not in new files, and removed from an existing (Rider) file.
        var rider = DesignerWriter.Encode(DesignerWriter.Render(withMaster, DesignerStyle.Rider), DesignerStyle.Rider);
        Assert.DoesNotContain("Property Master", DesignerOutput.Decode(DesignerOutput.Build(withMaster, null, new OutputOptions())));
        Assert.DoesNotContain("Property Master", DesignerOutput.Decode(DesignerOutput.Build(withMaster, rider, new OutputOptions())));

        // --master keep: whatever the existing file does.
        var kept = Build(rider, MasterPropertyMode.Keep);
        Assert.Contains("Public Shadows ReadOnly Property Master() As App.Site", kept);
        Assert.Contains("Return CType(MyBase.Master, App.Site)", kept);
        Assert.DoesNotContain("Property Master", Build(null, MasterPropertyMode.Keep));

        // --master always.
        Assert.Contains("Property Master", Build(null, MasterPropertyMode.Always));
    }

    [Fact]
    public void Namespace_block_matches_visual_studio()
    {
        // Saved by Visual Studio 2022 for a page whose class is in `Namespace WfToolsTest` (the file had no BOM
        // before VS regenerated it, and VS keeps the existing encoding).
        var vs = File.ReadAllBytes(Path.Combine(AppContext.BaseDirectory, "Fixtures", "VisualStudio", "Namespaced.aspx.designer.vb"));
        const string Web = "Global.System.Web.UI.WebControls.";
        const string Html = "Global.System.Web.UI.HtmlControls.";
        var model = new DesignerModel
        {
            ClassName = "NsTest",
            Namespace = "WfToolsTest",
            Fields =
            [
                new("lblTitle", Web + "Label", default),
                new("divBox", Html + "HtmlGenericControl", default),
                new("txtValue", Web + "TextBox", default),
                new("tblTest", Html + "HtmlTable", default),
                new("rowTest", Html + "HtmlTableRow", default),
                new("litCell", Web + "Literal", default),
                new("ucTest", "Global.SampleApp.WfToolsTest.NsTestControl", default),
            ],
            MasterTypeName = null,
        };

        Assert.Equal(Encoding.UTF8.GetString(vs), DesignerWriter.Render(model, DesignerStyle.VisualStudio));
        Assert.Equal(vs, DesignerWriter.Encode(DesignerWriter.Render(model, DesignerStyle.Detect(vs)), DesignerStyle.Detect(vs)));
    }

    [Fact]
    public void Existing_designer_parse()
    {
        var parsed = ExistingDesigner.Parse(VisualStudioText);
        Assert.Equal("Blank", parsed.ClassName);
        Assert.Equal([("form1", "Global.System.Web.UI.HtmlControls.HtmlForm")], parsed.Fields);
    }
}
